"""Topic scopes of the cluster (design doc 13.7) and the broker's access rules.

    master account   publish and subscribe under scenegems/<master_id>/#
    node account     publish and subscribe under scenegems/<master_id>/<node_id>/#
    anything else    denied, including $SYS and the workbench topics

A node account's username is its node id, so one rule with NanoMQ's `${username}`
placeholder covers every node. NanoMQ checks a subscription's filter against the rule
as a whole, so `scenegems/<master_id>/+/#` or `#` from a node is refused as well.
"""

import json
from dataclasses import dataclass
from typing import Optional, Sequence

from scenegems_tool.cluster.security.scope_names import ensure_scope_name

CLUSTER_TOPIC_ROOT = "scenegems"
USERNAME_PLACEHOLDER = "${username}"


def master_topic_scope(master_id: str) -> str:
    return f"{CLUSTER_TOPIC_ROOT}/{ensure_scope_name(master_id, 'master id')}"


def node_topic_scope(master_id: str, node_id: str) -> str:
    """The prefix every topic of the node's subsystem instances starts with."""
    return f"{master_topic_scope(master_id)}/{ensure_scope_name(node_id, 'node id')}"


@dataclass(frozen=True)
class AccessRule:
    permit: str  # "allow" or "deny"
    action: Optional[str] = None  # "publish", "subscribe" or "pubsub"; None means any
    topics: Sequence[str] = ()
    username: Optional[str] = None  # None means every account

    def to_nanomq(self) -> str:
        entry: dict = {"permit": self.permit}
        if self.username is not None:
            entry["username"] = self.username
        if self.action is not None:
            entry["action"] = self.action
        if self.topics:
            entry["topics"] = list(self.topics)
        return json.dumps(entry)


def cluster_access_rules(master_id: str, master_username: str) -> list[AccessRule]:
    ensure_scope_name(master_username, "master broker username")
    master_scope = master_topic_scope(master_id)
    return [
        AccessRule(permit="allow", username=master_username, action="pubsub", topics=(f"{master_scope}/#",)),
        AccessRule(permit="allow", action="pubsub", topics=(f"{master_scope}/{USERNAME_PLACEHOLDER}/#",)),
        AccessRule(permit="deny"),
    ]


def render_access_rules(rules: Sequence[AccessRule]) -> str:
    """The file NanoMQ includes as `auth.acl`; rules are matched top to bottom."""
    lines = ["# Generated by scenegems_tool.cluster.security; edits are overwritten.", "rules = ["]
    lines += [f"  {rule.to_nanomq()}" for rule in rules]
    lines.append("]")
    return "\n".join(lines) + "\n"
