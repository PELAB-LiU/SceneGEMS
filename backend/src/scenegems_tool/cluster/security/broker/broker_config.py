"""The NanoMQ configuration of the master's cluster broker.

The cluster broker serves MQTT over TLS only, with the server certificate the master's CA
issued. Anonymous clients are refused. Every login is checked by the master through an
HTTP hook that carries a shared secret, and every publish and subscribe goes through the
access rules from access_rules.py.

A denied subscription gets a failure code in its SUBACK (`deny_action = ignore`). A denied
publish closes the publisher's connection: NanoMQ 0.25 does that for every QoS whatever
`deny_action` says (measured, design doc 13.8).

The workbench keeps its own plain broker (deploy/workbench/docker-compose.yml, service
`broker`, bound to 127.0.0.1): NanoMQ applies one authentication setting to all
listeners, so a plain anonymous listener cannot live in the same broker as the cluster's.

The paths below are inside the broker container, where the master's
`<security folder>/broker` is mounted read-only at BROKER_CONFIG_MOUNT.
"""

import re
from dataclasses import dataclass

BROKER_CONFIG_MOUNT = "/etc/scenegems/broker"
CONFIG_FILE_NAME = "nanomq.conf"
ACCESS_RULES_FILE_NAME = "nanomq_acl.conf"
TLS_FOLDER_NAME = "tls"
CERTIFICATE_FILE_NAME = "server_certificate.pem"
KEY_FILE_NAME = "server_key.pem"
CA_CERTIFICATE_FILE_NAME = "ca_certificate.pem"
TLS_PORT = 8883
# NanoMQ always opens a TLS WebSocket listener; this keeps it on the container's loopback.
UNUSED_WEBSOCKET_BIND = "127.0.0.1:8086/mqtt"

_HOOK_SECRET_PATTERN = re.compile(r"^[A-Za-z0-9_-]{32,}$")
_HOOK_URL_PATTERN = re.compile(r"^https?://[A-Za-z0-9._:\-\[\]]+(/[A-Za-z0-9._~/\-]*)?$")


@dataclass(frozen=True)
class ClusterBrokerSettings:
    auth_hook_url: str  # the master's auth hook as the broker container reaches it
    auth_hook_secret: str

    def __post_init__(self) -> None:
        if not _HOOK_URL_PATTERN.fullmatch(self.auth_hook_url):
            raise ValueError(f"Invalid broker auth hook URL {self.auth_hook_url!r}")
        if not _HOOK_SECRET_PATTERN.fullmatch(self.auth_hook_secret):
            raise ValueError("The broker auth hook secret must have at least 32 characters from A-Z, a-z, 0-9, '_' and '-'")

    def __repr__(self) -> str:
        return f"ClusterBrokerSettings(auth_hook_url={self.auth_hook_url!r}, auth_hook_secret=<hidden>)"


def render_broker_config(settings: ClusterBrokerSettings) -> str:
    tls = f"{BROKER_CONFIG_MOUNT}/{TLS_FOLDER_NAME}"
    return f"""# Generated by scenegems_tool.cluster.security; edits are overwritten.
# Cluster broker of one SceneGEMS master: TLS only, logins checked by the master.

mqtt {{
    property_size = 32
    max_packet_size = 256MB
    max_mqueue_len = 2048
    retry_interval = 10s
    keepalive_multiplier = 1.25
}}

listeners.ssl {{
    bind = "0.0.0.0:{TLS_PORT}"
    keyfile = "{tls}/{KEY_FILE_NAME}"
    certfile = "{tls}/{CERTIFICATE_FILE_NAME}"
    cacertfile = "{tls}/{CA_CERTIFICATE_FILE_NAME}"
    verify_peer = false
    fail_if_no_peer_cert = false
}}

listeners.wss {{
    bind = "{UNUSED_WEBSOCKET_BIND}"
}}

log {{
    to = [console]
    level = warn
}}

auth {{
    allow_anonymous = false
    no_match = deny
    deny_action = ignore
    cache = {{
        max_size = 1024
        ttl = 1m
    }}
    acl = {{include "{BROKER_CONFIG_MOUNT}/{ACCESS_RULES_FILE_NAME}"}}
    http_auth = {{
        auth_req {{
            url = "{settings.auth_hook_url}"
            method = "POST"
            headers.content-type = "application/x-www-form-urlencoded"
            headers.authorization = "Bearer {settings.auth_hook_secret}"
            params = {{clientid = "%c", username = "%u", password = "%P"}}
        }}
        timeout = 5s
        connect_timeout = 5s
        pool_size = 8
    }}
}}
"""
